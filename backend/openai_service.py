def _is_placeholder_value(value: Any) -> bool:
    text = _clean_text(value).strip(" .:-")
    if not text:
        return True
    return bool(re.fullmatch(
        r"(?i)(?:untitled|unknown|not specified|not provided|n/?a|none|null|"
        r"education|degree|school|college|university|placeholder|tbd|to be decided)",
        text,
    ))


def _normalize_education(raw: Any) -> list[dict[str, Any]]:
    items = raw if isinstance(raw, list) else ([raw] if raw else [])
    normalized = []

    for item in items:
        if not isinstance(item, dict):
            text = _clean_text(item)
            if not _is_placeholder_value(text):
                normalized.append({
                    "degree": text,
                    "institution": "",
                    "dates": "",
                    "details": [],
                })
            continue

        degree = _clean_text(
            item.get("degree")
            or item.get("qualification")
            or item.get("program")
            or item.get("name")
            or item.get("title")
        )
        institution = _clean_text(
            item.get("institution")
            or item.get("university")
            or item.get("college")
            or item.get("school")
        )
        dates = _clean_text(
            item.get("dates")
            or item.get("date")
            or item.get("period")
        )

        details_raw = item.get("details", [])
        if isinstance(details_raw, dict):
            details: list[str] = []
            for key, value in details_raw.items():
                values = _string_list(value)
                label = _title_case_key(key)
                for value_text in values:
                    details.append(f"{label}: {value_text}" if label else value_text)
        else:
            details = _string_list(details_raw)

